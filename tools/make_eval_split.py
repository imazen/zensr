#!/usr/bin/env python3
"""Re-derive the imazen-26 train/val/test split from the canonical corpus.

Replaces the old **"first-8-sorted ∪ a pinned list of 64"** scheme, which was
never a split — it was a hand-maintained exclusion list invented because the
pre-curation corpus had no ids to split on. It leaked twice (the `teresa`
incident: the runtime's "first 8 *usable*" slid past a 101 MP decode-skip and
admitted file 9 into training), and its directory keys name a corpus that no
longer exists.

The canonical corpus has ids, so the canonical rule applies — see
`tools/origin_split.py` for the rule and the grouping it needs.

Writes two files, deliberately:

* `imazen26_split.tsv` — the authoritative artifact: every file, its origin, and
  its bucket. Five columns.
* `imazen26_eval_files.tsv` — the pin the existing harnesses parse, regenerated.
  **Exactly two columns (folder, filename)**, because that is what
  `zensr-bench/src/lib.rs` `load_pinned`, `gen_detect.rs` and the leakage audits
  all read; a third column silently breaks one of the three parsers. It lists
  val ∪ test, i.e. everything training must not see.

Usage: make_eval_split.py [--check]   (--check verifies without writing)
"""
import collections
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from imazen26_canonical import manifest_rows  # noqa: E402
from corpus_split import group_key, split_map  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "eval_split")

HEADER = """\
# imazen-26 train/val/test split — CANONICAL corpus (~/work/codec-corpus/imazen-26).
# Generated by tools/make_eval_split.py on {date}; do not hand-edit.
#
# Rule: zenmetrics scripts/picker/origin_split.py — trailing digit of the leading
# integer id, {{0,2,4,6,8}} train / {{1,3,5}} val / {{7,9}} test — applied to each
# ORIGIN's minimum id, with every file of the origin inheriting it. Origins are
# grouped by (folder, descriptor), falling back to the filename stem when the
# descriptor is empty (see tools/origin_split.py for why that fallback matters).
#
# This SUPERSEDES the "first-8-sorted UNION pinned" exclusion scheme, whose keys
# were the deleted /mnt/v/imazen-26 flat layout. Training excludes by BUCKET now:
# a file is training data iff its bucket is train. There is no first-N rule left
# to slide.
"""


def main():
    rows = manifest_rows()
    sm = split_map(rows)
    gk = {r["path"]: group_key(r) for r in rows}
    date = "2026-09-07"

    split_lines = [HEADER.format(date=date),
                   "# folder\tfilename\tbucket\torigin\tid\n"]
    pin_lines = [HEADER.format(date=date),
                 "# Val UNION test — the files training must never see.\n",
                 "# folder\tfilename  (two columns only; parsers depend on it)\n"]
    counts = collections.Counter()
    for r in sorted(rows, key=lambda r: r["path"]):
        folder, fname = r["path"].split("/", 1)
        b = sm[r["path"]]
        counts[b] += 1
        split_lines.append(f"{folder}\t{fname}\t{b}\t{gk[r['path']][1]}\t{r['number']}\n")
        if b != "train":
            pin_lines.append(f"{folder}\t{fname}\n")

    if "--check" in sys.argv:
        print(f"would write {counts['train']} train / {counts['val']} val / "
              f"{counts['test']} test")
        return
    with open(os.path.join(OUT, "imazen26_split.tsv"), "w") as f:
        f.writelines(split_lines)
    with open(os.path.join(OUT, "imazen26_eval_files.tsv"), "w") as f:
        f.writelines(pin_lines)
    print(f"wrote eval_split/imazen26_split.tsv  ({len(rows)} files)")
    print(f"wrote eval_split/imazen26_eval_files.tsv "
          f"({counts['val'] + counts['test']} eval files, was 64)")
    print(f"  train {counts['train']}  val {counts['val']}  test {counts['test']}")


if __name__ == "__main__":
    main()
