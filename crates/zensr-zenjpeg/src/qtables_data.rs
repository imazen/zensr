//! provenance but says nothing about the quantiser — a survey of 17,739 corpus
//! JPEGs found it reports `ImageMagick` for 9,626 files of which only 180
//! actually use the ImageMagick/Robidoux table. Since the projection slack is
//! a claim about quantiser BEHAVIOUR, it wants the table, not the marker.
//!
